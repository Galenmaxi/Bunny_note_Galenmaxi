-- Bunnynote database schema (Supabase / Postgres).
-- Derived from what bunnynote-site/index.html reads and writes.
-- Run once in Supabase Dashboard -> SQL Editor on a NEW project, then put the
-- project's URL and anon key into SB_URL / SB_KEY in index.html.
--
-- Rules the app depends on:
--   * every table has an "id" column (the app sorts every query by id, settings included)
--   * notes.tags is a text array (the app sends a JSON array of strings)
--   * deleting a habit must also delete its completions (on delete cascade)

create table if not exists tasks (
  id          bigint generated by default as identity primary key,
  text        text not null,
  cat         text not null default 'academic',   -- academic | creative | life
  priority    text not null default 'mid',        -- high | mid | low
  done        boolean not null default false,
  recurring   text not null default '',           -- '' | daily | weekly
  deadline    date,
  created_at  timestamptz not null default now()
);

create table if not exists notes (
  id          bigint generated by default as identity primary key,
  title       text not null,
  content     text not null default '',           -- rich-text HTML
  folder      text not null default 'personal',   -- school | work | personal | ideas
  tags        text[] not null default '{}',
  deadline    date,
  domain      text,
  status      text not null default 'due',        -- due | tentative | done | open
  created_at  timestamptz not null default now()
);

create table if not exists goals (
  id           bigint generated by default as identity primary key,
  title        text not null,
  current_val  numeric not null default 0,
  target_val   numeric not null default 10,
  unit         text not null default '',
  deadline     date,
  created_at   timestamptz not null default now()
);

create table if not exists habits (
  id          bigint generated by default as identity primary key,
  name        text not null,
  created_at  timestamptz not null default now()
);

create table if not exists habit_completions (
  id              bigint generated by default as identity primary key,
  habit_id        bigint not null references habits(id) on delete cascade,
  completed_date  date not null,
  unique (habit_id, completed_date)
);

create table if not exists projects (
  id          bigint generated by default as identity primary key,
  name        text not null,
  cat         text not null default 'Personal',   -- Work | Personal | School | Hobby
  created_at  timestamptz not null default now()
);

create table if not exists settings (
  id     bigint generated by default as identity primary key,
  key    text not null unique,                    -- name | mood | focus | reflection | cats
  value  text
);

-- ---------------------------------------------------------------------------
-- Access control
-- ---------------------------------------------------------------------------
-- RLS is always on. Until login is added (FIX-PLAN Phase 1) the app only has the
-- anon key, so a TEMPORARY policy lets anon read/write. Anyone with the anon key
-- (it is visible in index.html) can do the same, so treat the data as public
-- until Phase 1 replaces these policies.
do $$
declare t text;
begin
  foreach t in array array['tasks','notes','goals','habits','habit_completions','projects','settings']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "temp_anon_all" on %I', t);
    execute format('create policy "temp_anon_all" on %I for all to anon using (true) with check (true)', t);
  end loop;
end $$;

